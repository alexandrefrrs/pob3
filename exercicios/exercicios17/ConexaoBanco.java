package exercicios.exercicios17;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

public class ConexaoBanco {

    public static Connection conectar() throws SQLException {
        return DriverManager.getConnection("jdbc:h2:mem:exercicios17", "sa", "");
    }

    public static void prepararExemplo(Connection conn) throws SQLException {
        try (Statement stmt = conn.createStatement()) {
            stmt.executeUpdate("CREATE TABLE clientes (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome VARCHAR(100), email VARCHAR(150))");
            stmt.executeUpdate("CREATE TABLE produtos (id BIGINT PRIMARY KEY, nome VARCHAR(100), preco DOUBLE PRECISION, estoque INT)");
            stmt.executeUpdate("CREATE TABLE funcionarios (id BIGINT PRIMARY KEY, nome VARCHAR(100), salario DECIMAL(12, 2))");
            stmt.executeUpdate("CREATE TABLE logs_sistema (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, mensagem VARCHAR(1000), data_registro TIMESTAMP)");
            stmt.executeUpdate("CREATE TABLE contas (id BIGINT PRIMARY KEY, saldo DECIMAL(12, 2) NOT NULL CHECK (saldo >= 0))");

            stmt.executeUpdate("INSERT INTO produtos VALUES (1, 'Mouse', 60.00, 10), (2, 'Teclado', 140.00, 5), (3, 'Monitor', 900.00, 3)");
            stmt.executeUpdate("INSERT INTO funcionarios VALUES (1, 'Ana', 3000.00), (2, 'Carlos', 4000.00)");
            stmt.executeUpdate("INSERT INTO contas VALUES (1, 1000.00), (2, 500.00)");
        }
    }
}
