package exercicios.exercicios18;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

public class ConnectionFactory {

    public static Connection conectar() throws SQLException {
        return DriverManager.getConnection("jdbc:h2:mem:exercicios18;DB_CLOSE_DELAY=-1", "sa", "");
    }

    public static void prepararBanco() throws SQLException {
        try (Connection conn = conectar(); Statement stmt = conn.createStatement()) {
            stmt.executeUpdate("CREATE TABLE IF NOT EXISTS alunos (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome VARCHAR(100), matricula VARCHAR(30) UNIQUE)");
            stmt.executeUpdate("CREATE TABLE IF NOT EXISTS produtos (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, descricao VARCHAR(100), preco_unitario DECIMAL(12,2), quantidade_estoque INT)");
            stmt.executeUpdate("CREATE TABLE IF NOT EXISTS livros (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, titulo VARCHAR(150))");
            stmt.executeUpdate("CREATE TABLE IF NOT EXISTS clientes (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome VARCHAR(100), email VARCHAR(150) NOT NULL, cpf VARCHAR(11) NOT NULL UNIQUE)");
            stmt.executeUpdate("CREATE TABLE IF NOT EXISTS pedidos (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, cliente VARCHAR(100) NOT NULL)");
            stmt.executeUpdate("CREATE TABLE IF NOT EXISTS itens_pedido (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, pedido_id BIGINT NOT NULL REFERENCES pedidos(id), descricao VARCHAR(100) NOT NULL, quantidade INT NOT NULL CHECK (quantidade > 0), preco_unitario DECIMAL(12,2) NOT NULL CHECK (preco_unitario >= 0))");
        }
    }
}
